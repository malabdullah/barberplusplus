import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { I18nextProvider } from 'react-i18next';
import i18next from 'i18next';
import en from '../../i18n/locales/en.json';
import BookingForm from './BookingForm';
import { packagesService } from '../../services/packages.service';
import { addBookingDays, getKuwaitDate } from '../../utils/customerBooking';
vi.mock('../../services/packages.service', () => ({ packagesService: { staff: vi.fn(), terms: vi.fn() } }));
vi.mock('../../hooks/useGeoLocation', () => ({ useGeoLocation: () => ({ dialCode: '+965' }) }));
vi.mock('../../hooks/useCustomerLookup', () => ({ useCustomerLookup: () => ({ customer: null, loading: false, isNewCustomer: false }) }));
afterEach(cleanup);
it('edits a purchased package using its original displayed price and duration after the offer changes', async () => {
  const date = addBookingDays(getKuwaitDate(), 1);
  const services = [{ id: 'beard', name: 'Beard', duration: 15, price: 2.5 }, { id: 'face', name: 'Facial', duration: 60, price: 10 }, { id: 'wash', name: 'Wash', duration: 20, price: 3 }];
  const historical = { id: 'offer', name: 'Original package', price: 10, duration: 75, regularPrice: 12.5, serviceIds: ['beard', 'face'], startsOn: getKuwaitDate(), endsOn: addBookingDays(date, 14) };
  packagesService.staff.mockResolvedValue([{ ...historical, name: 'Changed offer', price: 9 }]);
  packagesService.terms.mockResolvedValue(historical);
  const booking = { id: 'booking', barberId: 'barber', customerId: 'customer', customerName: 'QA Customer', customerPhone: '56988703', customerCountryCode: '+965', date, time: '12:00', price: 13, duration: 95, serviceIds: ['beard', 'face', 'wash'], serviceSnapshot: services, packageOfferId: 'offer', packageSnapshot: { name: 'Original package', price: 10, service_ids: ['beard', 'face'], starts_on: historical.startsOn, ends_on: historical.endsOn } };
  const availability = Object.fromEntries(['monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday'].map(day => [day, { enabled: true, start: '09:00', end: '21:00' }]));
  const barber = { id: 'barber', branchId: 'shop', name: 'QA Barber', services: ['beard', 'face', 'wash'], availability, timeOffs: [], vacations: [] };
  const i18n = i18next.createInstance(); await i18n.init({ lng: 'en', resources: { en: { translation: en } }, interpolation: { escapeValue: false } });
  const onSubmit = vi.fn().mockResolvedValue({});
  const { container } = render(<I18nextProvider i18n={i18n}><BookingForm booking={booking} barbers={[barber]} services={services} onSubmit={onSubmit} onCancel={vi.fn()} /></I18nextProvider>);
  const choice = await screen.findByRole('radio', { name: /Original package/ });
  await waitFor(() => expect(choice).toBeEnabled());
  expect(choice).toBeChecked();
  expect(screen.queryByText('Changed offer')).not.toBeInTheDocument();
  expect(container.querySelector('.package-choice-price strong')).toHaveTextContent('10.000');
  expect(container.querySelector('.services-total')).toHaveTextContent('95');
  expect(container.querySelector('.services-total')).toHaveTextContent('13');
  fireEvent.submit(container.querySelector('form'));
  await waitFor(() => expect(onSubmit).toHaveBeenCalledWith(expect.objectContaining({ packageOfferId: 'offer', price: 13, duration: 95, serviceIds: ['beard', 'face', 'wash'] })));
});
