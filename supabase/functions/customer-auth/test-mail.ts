// Mail is delivered only to the isolated local Inbucket container. The caller
// is the loopback-gated Test handler; no external SMTP host is configurable.
import { createClient } from 'https://esm.sh/@supabase/supabase-js@2.89.0';

export async function sendTestEmail(to: string, subject: string, link: string): Promise<void> {
  if (Deno.env.get('APP_ENV') === 'cloud-test') {
    const ref = Deno.env.get('CLOUD_TEST_PROJECT_REF');
    const url = Deno.env.get('SUPABASE_URL');
    if (!ref || url !== `https://${ref}.supabase.co`) throw Error('UNAVAILABLE');
    const admin = createClient(url, Deno.env.get('SUPABASE_SERVICE_ROLE_KEY') || '', {auth:{persistSession:false}});
    const { error } = await admin.rpc('cloud_test_mailbox', {p_action:'capture',p_data:{recipient:to,subject,link}});
    if (error) throw Error('UNAVAILABLE');
    return;
  }
  const conn = await Deno.connect({ hostname: 'inbucket', port: 1025 });
  const encoder = new TextEncoder(); const decoder = new TextDecoder();
  let pending = '';
  const read = async () => {
    while (true) {
      const lines = pending.split('\r\n');
      for (let i=0;i<lines.length-1;i++) {
        if (/^\d{3} /.test(lines[i])) {
          const code=Number(lines[i].slice(0,3)); pending=lines.slice(i+1).join('\r\n');
          if(code>=400)throw Error('UNAVAILABLE'); return;
        }
      }
      const buf=new Uint8Array(4096);const n=await conn.read(buf);if(!n)throw Error('UNAVAILABLE');pending+=decoder.decode(buf.subarray(0,n));
      if(pending.length>16384)throw Error('UNAVAILABLE');
    }
  };
  const write = async (text: string) => {const bytes=encoder.encode(text);let offset=0;while(offset<bytes.length)offset+=await conn.write(bytes.subarray(offset));};
  const command = async (value: string) => {await write(value+'\r\n');await read();};
  try {
    await read();await command('EHLO localhost');await command('MAIL FROM:<barber-test@example.test>');
    await command(`RCPT TO:<${to}>`);await command('DATA');
    await write(`From: Barber++ Test <barber-test@example.test>\r\nTo: <${to}>\r\nSubject: ${subject}\r\nContent-Type: text/plain; charset=utf-8\r\n\r\nOpen this link to continue:\r\n${link}\r\n\r\nThis message was generated by local Test.\r\n.\r\n`);
    await read();await command('QUIT');
  } finally {conn.close();}
}
